import type { Metadata } from "next";
import MainframeBg from "@/components/MainframeBg/MainframeBg";
import "./globals.css";
import localFont from "next/font/local";
import { Providers } from "./providers";
import { Geist, Geist_Mono, Kurale, Monomakh } from "next/font/google";

const bulgaria = localFont({
   src: "../../public/fonts/Bulgaria Moderna Pro/Bulgaria Moderna Pro.otf",
   variable: "--font-bulgaria",
   display: "swap",
});

const geistSans = Geist({
   variable: "--font-geist-sans",
   subsets: ["latin"],
});

const geistMono = Geist_Mono({
   variable: "--font-geist-mono",
   subsets: ["latin"],
});

const body = Kurale({
   weight: "400",
   subsets: ["latin", "cyrillic"],
   variable: "--font-decorative-face",
   display: "swap",
});

const display = Monomakh({
   weight: "400",
   subsets: ["latin", "cyrillic"],
   variable: "--font-display-face",
   display: "swap",
});

export const metadata: Metadata = {
   title: "D&D Alex Yad",
   description: "Generated by create next app",
};

export default function RootLayout({
   children,
}: Readonly<{
   children: React.ReactNode;
}>) {
   return (
      <html
         lang="en"
         className={`${geistSans.variable} ${geistMono.variable} ${bulgaria.variable} ${body.variable} ${display.variable} h-full antialiased`}
         suppressHydrationWarning
      >
         <head>
            <script
               dangerouslySetInnerHTML={{
                  __html: `try{var t=localStorage.getItem("theme");if(t==="dark"||(!t&&matchMedia("(prefers-color-scheme: dark)").matches))document.documentElement.classList.add("dark")}catch(e){}`,
               }}
            />
         </head>
         <body className="min-h-full flex flex-col bg-background">
            <Providers>
               <MainframeBg />
               {children}
            </Providers>
         </body>
      </html>
   );
}
